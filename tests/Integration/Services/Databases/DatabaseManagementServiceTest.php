<?php

namespace Tests\Integration\Services\Databases;

use App\Exceptions\Repository\DuplicateDatabaseNameException;
use App\Exceptions\Service\Database\DatabaseClientFeatureNotEnabledException;
use App\Exceptions\Service\Database\TooManyDatabasesException;
use App\Models\Database;
use App\Models\DatabaseHost;
use App\Repositories\Eloquent\DatabaseRepository;
use App\Services\Databases\DatabaseManagementService;
use Illuminate\Support\Str;
use Mockery\MockInterface;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\Integration\IntegrationTestCase;

class DatabaseManagementServiceTest extends IntegrationTestCase
{
    private MockInterface $repository;

    /**
     * Setup tests.
     */
    protected function setUp(): void
    {
        parent::setUp();

        config()->set('panel.client_features.databases.enabled', true);

        $this->repository = $this->mock(DatabaseRepository::class);
    }

    /**
     * Test that the name generated by the unique name function is what we expect.
     */
    public function test_unique_database_name_is_generated_correctly()
    {
        $this->assertSame('s1_example', DatabaseManagementService::generateUniqueDatabaseName('example', 1));
        $this->assertSame('s123_something_else', DatabaseManagementService::generateUniqueDatabaseName('something_else', 123));
        $this->assertSame('s123_'.Str::repeat('a', 43), DatabaseManagementService::generateUniqueDatabaseName(Str::repeat('a', 100), 123));
    }

    /**
     * Test that disabling the client database feature flag prevents the creation of databases.
     */
    public function test_exception_is_thrown_if_client_databases_are_not_enabled()
    {
        config()->set('panel.client_features.databases.enabled', false);

        $this->expectException(DatabaseClientFeatureNotEnabledException::class);

        $server = $this->createServerModel();
        $this->getService()->create($server, []);
    }

    /**
     * Test that a server at its database limit cannot have an additional one created if
     * the $validateDatabaseLimit flag is not set to false.
     */
    public function test_database_cannot_be_created_if_server_has_reached_limit()
    {
        $server = $this->createServerModel(['database_limit' => 2]);
        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);

        Database::factory()->times(2)->create(['server_id' => $server->id, 'database_host_id' => $host->id]);

        $this->expectException(TooManyDatabasesException::class);

        $this->getService()->create($server, []);
    }

    /**
     * Test that a missing or invalid database name format causes an exception to be thrown.
     */
    #[DataProvider('invalidDataDataProvider')]
    public function test_empty_database_name_or_invalid_name_triggers_an_exception(array $data)
    {
        $server = $this->createServerModel();

        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage('The database name passed to DatabaseManagementService::handle MUST be prefixed with "s{server_id}_".');

        $this->getService()->create($server, $data);
    }

    /**
     * Test that creating a server database with an identical name triggers an exception.
     */
    public function test_creating_database_with_identical_name_triggers_an_exception()
    {
        $server = $this->createServerModel();
        $name = DatabaseManagementService::generateUniqueDatabaseName('soemthing', $server->id);

        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);
        $host2 = DatabaseHost::factory()->create(['node_id' => $server->node_id]);
        Database::factory()->create([
            'database' => $name,
            'database_host_id' => $host->id,
            'server_id' => $server->id,
        ]);

        $this->expectException(DuplicateDatabaseNameException::class);
        $this->expectExceptionMessage('A database with that name already exists for this server.');

        // Try to create a database with the same name as a database on a different host. We expect
        // this to fail since we don't account for the specific host when checking uniqueness.
        $this->getService()->create($server, [
            'database' => $name,
            'database_host_id' => $host2->id,
        ]);

        $this->assertDatabaseMissing('databases', ['server_id' => $server->id]);
    }

    /**
     * Test that a server database can be created successfully.
     */
    public function test_server_database_can_be_created()
    {
        $server = $this->createServerModel();
        $name = DatabaseManagementService::generateUniqueDatabaseName('soemthing', $server->id);

        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);

        $this->repository->expects('createDatabase')->with($name, false);

        $username = null;
        $secondUsername = null;
        $password = null;

        // The value setting inside the closures if to avoid throwing an exception during the
        // assertions that would get caught by the functions catcher and thus lead to the exception
        // being swallowed incorrectly.
        $this->repository->expects('createUser')->with(
            \Mockery::on(function ($value) use (&$username) {
                $username = $value;

                return true;
            }),
            '%',
            \Mockery::on(function ($value) use (&$password) {
                $password = $value;

                return true;
            }),
            null
        );

        $this->repository->expects('assignUserToDatabase')->with($name, \Mockery::on(function ($value) use (&$secondUsername) {
            $secondUsername = $value;

            return true;
        }), '%');

        $this->repository->expects('flush')->withNoArgs();

        $response = $this->getService()->create($server, [
            'remote' => '%',
            'database' => $name,
            'database_host_id' => $host->id,
        ]);

        $this->assertInstanceOf(Database::class, $response);
        $this->assertSame($response->server_id, $server->id);
        $this->assertMatchesRegularExpression('/^(u\d+_)(\w){10}$/', $username);
        $this->assertSame($username, $secondUsername);
        $this->assertSame(24, strlen($password));

        $this->assertDatabaseHas('databases', ['server_id' => $server->id, 'id' => $response->id]);
    }

    /**
     * Test that an exception encountered after the database is created leads to the cleanup code
     * being called and any exceptions encountered while cleaning up go unreported.
     */
    public function test_exception_encountered_while_creating_database_attempts_to_cleanup()
    {
        $server = $this->createServerModel();
        $name = DatabaseManagementService::generateUniqueDatabaseName('soemthing', $server->id);

        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);

        $this->repository->expects('createDatabase')->with($name, false);
        $this->repository->expects('createUser')->withAnyArgs();
        $this->repository->expects('assignUserToDatabase')->withAnyArgs()->andThrows(new \BadMethodCallException());
        $this->repository->expects('dropDatabase')->with($name);
        $this->repository->expects('dropUser')->withAnyArgs()->andThrows(new \InvalidArgumentException());

        try {
            $this->getService()->create($server, [
                'remote' => '%',
                'database' => $name,
                'database_host_id' => $host->id,
            ]);

            $this->fail('Expected database creation to fail.');
        } catch (\BadMethodCallException) {
        }

        $this->assertDatabaseMissing('databases', ['server_id' => $server->id]);
    }

    /**
     * Test that a database which already exists on the host is not dropped when creation fails,
     * and that a user which was never created is not dropped either.
     */
    public function test_cleanup_does_not_drop_resources_it_did_not_create()
    {
        $server = $this->createServerModel();
        $name = DatabaseManagementService::generateUniqueDatabaseName('restored', $server->id);

        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);

        $this->repository->expects('createDatabase')->with($name, false)->andThrows(new \RuntimeException('Database exists'));
        $this->repository->shouldNotReceive('createUser');
        $this->repository->shouldNotReceive('dropDatabase');
        $this->repository->shouldNotReceive('dropUser');

        try {
            $this->getService()->create($server, [
                'remote' => '%',
                'database' => $name,
                'database_host_id' => $host->id,
            ]);

            $this->fail('Expected database creation to fail.');
        } catch (\RuntimeException $exception) {
            $this->assertSame('Database exists', $exception->getMessage());
        }

        $this->assertDatabaseMissing('databases', ['server_id' => $server->id]);
    }

    /**
     * Test that a failure creating the user only drops the database this request created.
     */
    public function test_failed_user_creation_only_drops_created_database()
    {
        $server = $this->createServerModel();
        $name = DatabaseManagementService::generateUniqueDatabaseName('something', $server->id);

        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);

        $this->repository->expects('createDatabase')->with($name, false);
        $this->repository->expects('createUser')->withAnyArgs()->andThrows(new \RuntimeException('Access denied'));
        $this->repository->expects('dropDatabase')->with($name);
        $this->repository->shouldNotReceive('dropUser');
        $this->repository->expects('flush')->withNoArgs();

        try {
            $this->getService()->create($server, [
                'remote' => '%',
                'database' => $name,
                'database_host_id' => $host->id,
            ]);

            $this->fail('Expected database creation to fail.');
        } catch (\RuntimeException $exception) {
            $this->assertSame('Access denied', $exception->getMessage());
        }

        $this->assertDatabaseMissing('databases', ['server_id' => $server->id]);
    }

    public function test_sequential_creation_enforces_the_database_limit(): void
    {
        $server = $this->createServerModel(['database_limit' => 1]);
        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);
        $this->repository->shouldReceive('createDatabase', 'createUser', 'assignUserToDatabase', 'flush')->once();

        $this->getService()->create($server, [
            'database' => "s{$server->id}_first",
            'database_host_id' => $host->id,
            'remote' => '%',
        ]);

        $this->assertSame(1, $server->databases()->count());
        $this->expectException(TooManyDatabasesException::class);
        $this->getService()->create($server, [
            'database' => "s{$server->id}_second",
            'database_host_id' => $host->id,
            'remote' => '%',
        ]);
    }

    public function test_commit_failure_cleans_up_created_host_resources(): void
    {
        $server = $this->createServerModel(['database_limit' => 1]);
        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);
        $name = "s{$server->id}_commit_failure";
        $connection = $this->app->make('db')->connection();
        $pdo = $connection->getPdo();
        $failingPdo = \Mockery::mock($pdo);
        $failingPdo->expects('commit')->andThrow(new \PDOException('Commit failed'));
        $connection->setPdo($failingPdo);
        $this->repository->expects('createDatabase')->with($name, false);
        $this->repository->expects('createUser');
        $this->repository->expects('assignUserToDatabase');
        $this->repository->expects('dropDatabase')->with($name);
        $this->repository->expects('dropUser');
        $this->repository->shouldReceive('flush')->twice();

        try {
            $this->getService()->create($server, [
                'database' => $name, 'database_host_id' => $host->id, 'remote' => '%',
            ]);
            $this->fail('Expected the panel commit to fail.');
        } catch (\PDOException $exception) {
            $this->assertSame('Commit failed', $exception->getMessage());
        } finally {
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }
            $connection->setPdo($pdo);
        }

        $this->assertDatabaseMissing('databases', ['server_id' => $server->id]);
    }

    public static function creationTransactionProvider(): array
    {
        return [[false], [true]];
    }

    #[DataProvider('creationTransactionProvider')]
    public function test_concurrent_creation_with_one_slot_remaining(bool $readBeforeLock): void
    {
        if (! function_exists('pcntl_fork') || config('database.connections.'.config('database.default').'.database') === ':memory:') {
            $this->markTestSkipped('Requires pcntl and a database shared between processes.');
        }

        if ($readBeforeLock && ! in_array($this->app->make('db')->connection()->getDriverName(), ['mysql', 'mariadb'])) {
            $this->markTestSkipped('Snapshot regression requires MySQL or MariaDB repeatable reads.');
        }

        $server = $this->createServerModel(['database_limit' => 1]);
        $host = DatabaseHost::factory()->create(['node_id' => $server->node_id]);
        $data = ['database_host_id' => $host->id, 'remote' => '%'];
        $sockets = stream_socket_pair(STREAM_PF_UNIX, STREAM_SOCK_STREAM, 0);
        $connection = $this->app->make('db')->connection();
        $connection->disconnect();
        $this->repository->shouldReceive('createDatabase', 'createUser', 'assignUserToDatabase', 'flush')->byDefault()->andReturn(true);
        $pid = pcntl_fork();
        $this->assertNotSame(-1, $pid);

        if ($pid === 0) {
            fclose($sockets[0]);
            stream_set_timeout($sockets[1], 10);
            fgets($sockets[1]);
            if ($readBeforeLock) {
                $connection->statement('SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ');
                $connection->beginTransaction();
                $server->databases()->count();
                fwrite($sockets[1], "snapshot\n");
            }
            $connection->beforeExecuting(function () use ($sockets, $readBeforeLock) {
                static $started = false;
                if (! $started && ! $readBeforeLock) {
                    fwrite($sockets[1], "attempting\n");
                    $started = true;
                }
            });
            try {
                $this->getService()->create($server, $data + ['database' => "s{$server->id}_second"]);
                if ($readBeforeLock) {
                    $connection->commit();
                }
                $result = 'created';
            } catch (TooManyDatabasesException) {
                $result = 'limit';
            } catch (\Throwable $exception) {
                $result = get_class($exception).': '.$exception->getMessage();
            }
            if ($connection->transactionLevel() > 0) {
                $connection->rollBack();
            }
            fwrite($sockets[1], $result."\n");
            fclose($sockets[1]);
            exit(0);
        }

        fclose($sockets[1]);
        stream_set_timeout($sockets[0], 10);
        $this->repository->expects('createDatabase')->andReturnUsing(function () use ($sockets, $readBeforeLock) {
            fwrite($sockets[0], "start\n");
            $this->assertSame($readBeforeLock ? "snapshot\n" : "attempting\n", fgets($sockets[0]));
            usleep(300000);

            return true;
        });
        $this->repository->shouldReceive('createUser', 'assignUserToDatabase', 'flush')->once();

        try {
            $this->getService()->create($server, $data + ['database' => "s{$server->id}_first"]);
            $result = trim(fgets($sockets[0]));
        } finally {
            fclose($sockets[0]);
            pcntl_waitpid($pid, $status);
        }

        $this->assertSame('limit', $result);
        $this->assertSame(1, $server->databases()->count());
    }

    public static function invalidDataDataProvider(): array
    {
        return [
            [[]],
            [['database' => '']],
            [['database' => 'something']],
            [['database' => 's_something']],
            [['database' => 's12s_something']],
            [['database' => 's12something']],
        ];
    }

    private function getService(): DatabaseManagementService
    {
        return $this->app->make(DatabaseManagementService::class);
    }
}
